#!/usr/bin/env python3
"""Collect the facts behind results/summary.md into results/facts.md (regenerate any time).

- Vendor jobs (jobs.json): latest build and run record, achieved clocks from the Vivado link log
  (AUTO-FREQ-SCALING messages) and the routed WNS.
- Platform modules (u50v_*): every record in artifacts/records.jsonl, plus the achieved clock of
  the hw build the record used.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
PLATFORM_ROOT = HERE.parent.parent
SCALE = re.compile(r"The (kernel|system) clock (\S+) has an original frequency equal to ([\d.]+) ?MHz\. "
                   r"The frequency has been automatically changed to ([\d.]+) MHz")


def latest(path: Path) -> dict[str, dict]:
    found: dict[str, dict] = {}
    if path.exists():
        for line in path.read_text().splitlines():
            if line.strip():
                record = json.loads(line)
                found[record["id"]] = record
    return found


def clocks(build_root: Path) -> str:
    """'kernel 300->219.3, hbm 450->320.8; WNS -1.226' or 'met' from the files under build_root."""
    logs = list(build_root.glob("_x_temp.hw.*/link/vivado/vpl/vivado.log")) or \
        list(build_root.glob("_x*/link/vivado/vpl/vivado.log")) or \
        list(build_root.glob("**/link/vivado/vpl/vivado.log"))
    notes: list[str] = []
    for log in logs[:1]:
        seen = set()
        for kind, name, before, after in SCALE.findall(log.read_text(errors="replace")):
            label = "hbm" if "hbm" in name else ("kernel" if kind == "kernel" else name)
            key = (label, before, after)
            if key not in seen:
                seen.add(key)
                notes.append(f"{label} {float(before):g}->{float(after):g} MHz")
    reports = list(build_root.glob("**/impl_1/*timing_summary_routed.rpt"))
    if reports:
        lines = reports[0].read_text(errors="replace").splitlines()
        for index, line in enumerate(lines):
            if line.strip().startswith("WNS(ns)"):
                notes.append(f"WNS {lines[index + 2].split()[0]} ns")
                break
    if not logs and not reports:
        return "-"
    return "; ".join(notes) if notes else "met"


def vendor_rows() -> list[str]:
    jobs = json.loads((HERE / "jobs.json").read_text())["jobs"]
    builds = latest(HERE / "results" / "builds.jsonl")
    runs = latest(HERE / "results" / "runs.jsonl")
    rows = ["| job | library | operation | build | run | verdict lines | clocks |", "|---|---|---|---|---|---|---|"]
    for job in jobs:
        build, run = builds.get(job["id"]), runs.get(job["id"])
        build_cell = (f"exit {build['exit_code']}, {build['seconds'] / 60:.0f} min" if build else
                      ("reused 2026-07/08 build" if job["id"].startswith("pre_") else "not built"))
        run_cell = f"exit {run['exit_code']}, {run['seconds']:.0f} s" if run else "not run"
        verdict = " / ".join(run.get("verdict_lines", [])[-3:]) if run else ""
        root = Path(job["root"]) / job["dir"]
        rows.append(f"| {job['id']} | {job['library']} | {job['operation']} | {build_cell} | {run_cell} | "
                    f"{verdict.replace('|', '/')[:220]} | {clocks(root)} |")
    return rows


def platform_rows() -> list[str]:
    rows = ["| run id | module | target | status | input bytes | validation | build | kernel ms | clocks |",
            "|---|---|---|---|---|---|---|---|---|"]
    records = PLATFORM_ROOT / "artifacts" / "records.jsonl"
    for line in records.read_text().splitlines():
        record = json.loads(line)
        if not str(record.get("module", "")).startswith("u50v_"):
            continue
        validation = record.get("validation") or {}
        build = record.get("build") or {}
        clock = clocks(Path(build["binary"]).parent) if build.get("binary") and record["target"] == "hw" else "-"
        rows.append(
            f"| {record['run_id']} | {record['module']} | {record['target']} | {record['status']} | "
            f"{record.get('input_bytes')} | {validation.get('mode', '-')}: {validation.get('passed')} "
            f"({str(validation.get('detail', ''))[:60]}) | {'cached' if build.get('cached') else 'built'} "
            f"{build.get('fingerprint', '')[:8]} | {(record.get('metrics') or {}).get('kernel_ms', '-')} | {clock} |")
    return rows


def main() -> None:
    text = ["# Facts (generated by tools/facts.py)", "", "## Vendor reference flow (V)", "",
            *vendor_rows(), "", "## Platform lifecycle (P)", "", *platform_rows(), ""]
    out = HERE / "results" / "facts.md"
    out.write_text("\n".join(text), encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
